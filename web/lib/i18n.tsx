const DICTS = { en, ar };

interface I18nCtx {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (l: Lang) => void;
  t: (k: DictKey) => string;
  fmtPrice: (n: number) => string;
  fmtNum: (n: number) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("uaeph-lang");
      if (saved === "ar" || saved === "en") setLangState(saved);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("uaeph-lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback((k: DictKey) => DICTS[lang][k] ?? en[k] ?? k, [lang]);
  const fmtNum = useCallback((n: number) => n.toLocaleString(lang === "ar" ? "ar-AE" : "en-US"), [lang]);
  const fmtPrice = useCallback((n: number) => (lang === "ar" ? `${n.toLocaleString("ar-AE")} درهم` : `AED ${n.toLocaleString("en-US")}`), [lang]);

  return <Ctx.Provider value={{ lang, dir: lang === "ar" ? "rtl" : "ltr", setLang, t, fmtPrice, fmtNum }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n must be used inside I18nProvider");
  return c;
}
